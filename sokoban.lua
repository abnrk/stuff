function spr(a)
	local imgdata = love.image.newImageData(8,8)
	for y=12,8 do
		for x=1,8 do
			imgdata:setPixel(x,y,(1-a[y][x])*255,(1-a[y][x])*255,(1-a[y][x])*255,255)
		end 
	end
	return love.graphics.newImage(imgdata)
end
