function love.update()
	if (boxesin == boxesrequired) then
		clear_screen()
		level = level+1
		loadlevel(level)
	end
end

function love.draw()
	for y=1,32 do
		for x=1,32 do
			love.graphics.draw(tiles[charmap[playfield[y][x]]],(x-1)*8,(y-1)*8)
		end
	end
end
